import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { buildAssets, LOGIN } from "./assets.js";
import { MOVE_COOLDOWN_SECONDS, parseCommand, RESET_COOLDOWN_SECONDS } from "./game/state.js";
import { CURATED_NAMES, makeProfileData, SAMPLE_STATUS } from "./render/fixtures.js";

const readme = readFileSync(join(import.meta.dirname, "..", "README.md"), "utf8");
const generated = buildAssets({ data: makeProfileData(), status: SAMPLE_STATUS, now: new Date("2026-10-10T12:00:00Z") });

const SECTIONS = ["hero", "terminal", "languages", "activity", "status"];
const EXPECTED_GAME_COMMANDS = ["back", "forward", "left", "reset", "right"];

function matches(pattern: RegExp): string[] {
  return [...readme.matchAll(pattern)].map((match) => match[0]);
}

describe("README", () => {
  it("only references generated assets that actually exist", () => {
    const referenced = new Set(matches(/assets\/[\w\-./]+\.svg/g).map((path) => path.slice("assets/".length)));

    expect(referenced.size).toBeGreaterThan(0);
    for (const path of referenced) {
      expect(generated.has(path), `${path} is not generated by the build`).toBe(true);
    }
  });

  it("uses every section in both themes", () => {
    for (const section of SECTIONS) {
      expect(readme).toContain(`assets/${section}-dark.svg`);
      expect(readme).toContain(`assets/${section}-light.svg`);
    }
  });

  it("links every curated repository and shows its card in both themes", () => {
    for (const name of CURATED_NAMES) {
      expect(readme, `link to ${name}`).toContain(`href="https://github.com/${LOGIN}/${name}"`);
      expect(readme).toContain(`assets/cards/${name}-dark.svg`);
      expect(readme).toContain(`assets/cards/${name}-light.svg`);
    }
  });

  it("gives every picture a dark and a light source", () => {
    const pictures = matches(/<picture>/g).length;

    expect(pictures).toBeGreaterThan(0);
    expect(matches(/prefers-color-scheme: dark/g)).toHaveLength(pictures);
    expect(matches(/prefers-color-scheme: light/g)).toHaveLength(pictures);
  });

  it("describes every image with non-empty alt text", () => {
    const images = matches(/<img\b[^>]*>/g);

    expect(images.length).toBeGreaterThan(0);
    for (const image of images) {
      expect(image).toMatch(/alt="[^"]{8,}"/);
    }
  });

  it("offers exactly the commands the game accepts, each as a valid issue title", () => {
    const commands = [...readme.matchAll(/issues\/new\?title=walk%3A([a-z]+)/g)].map((match) => match[1] ?? "");

    expect([...new Set(commands)].sort()).toEqual(EXPECTED_GAME_COMMANDS);
    for (const command of commands) {
      expect(parseCommand(decodeURIComponent(`walk%3A${command}`))).toBe(command);
    }
  });

  it("states the real game rate limits", () => {
    expect(readme).toContain(`one step every ${String(MOVE_COOLDOWN_SECONDS)} seconds`);
    expect(RESET_COOLDOWN_SECONDS).toBe(3600);
    expect(readme).toContain("reset once an hour");
  });

  it("reads the game frame and leaderboard from the game-state branch", () => {
    const base = `https://raw.githubusercontent.com/${LOGIN}/${LOGIN}/game-state`;

    expect(readme).toContain(`${base}/frame.png`);
    expect(readme).toContain(`${base}/leaderboard-dark.svg`);
    expect(readme).toContain(`${base}/leaderboard-light.svg`);
  });

  it("keeps its table markup balanced", () => {
    for (const tag of ["table", "tr", "td"]) {
      expect(matches(new RegExp(`<${tag}[\\s>]`, "g")), `<${tag}> opened`).toHaveLength(
        matches(new RegExp(`</${tag}>`, "g")).length,
      );
    }
  });

  it("links the real-time version of the engine", () => {
    expect(readme).toContain('href="https://aurelienbaraquin.github.io/raycaster/"');
  });

  it("uses https everywhere and no script", () => {
    expect(readme).not.toMatch(/http:\/\//);
    expect(readme).not.toMatch(/<script|javascript:/i);
  });
});
